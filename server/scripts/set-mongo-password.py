# -*- coding: utf-8 -*-
"""
Change the password in server/.env's MONGO_URI without typing it anywhere
it can be read back.

    cd server && python scripts/set-mongo-password.py

The prompt does not echo, so the password is not on screen, not on a
command line and not in your shell history. Everything else about the
connection string -- user, cluster, database, options -- is taken from the
MONGO_URI already in the file and put back unchanged, so this script holds
no deployment details of its own and nothing identifying it is committed.

Why it exists: a connection string is a password with a URL wrapped round
it, and the two easy ways to get one into a file -- pasting it into a chat
and echoing it on a command line -- both leave a copy somewhere you did
not intend.
"""
import getpass
import io
import os
import re
import sys

try:
    from urllib.parse import quote
except ImportError:                                     # Python 2
    from urllib import quote

HERE = os.path.dirname(os.path.abspath(__file__))
ENV = os.path.normpath(os.path.join(HERE, '..', '.env'))

PLACEHOLDERS = ('THEPASSWORD', 'PASSWORD', 'password',
                '<db_password>', 'db_password')

if not os.path.exists(ENV):
    sys.exit('cannot find %s -- copy .env.example to .env first' % ENV)

raw = io.open(ENV, encoding='utf-8', newline='').read()
crlf = '\r\n' in raw
flat = raw.replace('\r\n', '\n') if crlf else raw

line = re.compile(r'(?m)^([ \t]*MONGO_URI[ \t]*=)(.*)$')
match = line.search(flat)
if not match:
    sys.exit('no MONGO_URI line in %s' % ENV)

current = match.group(2).strip().strip('"').strip("'")
if '://' not in current:
    sys.exit('MONGO_URI in %s is not a URI' % ENV)

scheme, rest = current.split('://', 1)
if '@' not in rest:
    sys.exit(
        'MONGO_URI in %s has no user in it, so there is no password to\n'
        'change. Paste the connection string from Atlas into that line\n'
        'first (the password can stay as a placeholder), then run this\n'
        'again.' % ENV)

credentials, location = rest.split('@', 1)
user = credentials.split(':', 1)[0]
host = location.split('/')[0]
database = location.split('/')[1].split('?')[0] if '/' in location else ''

print('')
print('User     : %s' % user)
print('Cluster  : %s' % host)
print('Database : %s' % (database or '(none -- Mongoose will use "test")'))
print('File     : %s' % ENV)
print('')
print('Type or paste the password and press Enter. Nothing will appear as')
print('you type -- that is the point, not a broken prompt.')
print('')

secret = getpass.getpass('Password: ')

# Pasting the whole connection string instead of just the password is an
# easy mistake; take the password out of it rather than failing.
if secret.strip().startswith('mongodb'):
    pasted = secret.strip().split('://', 1)[-1].split('@')[0]
    if ':' not in pasted:
        sys.exit('\nthat is a connection string with no password in it')
    secret = pasted.split(':', 1)[1]
    print('\n(that was a whole connection string -- using the password from it)')

# Atlas autogenerated passwords are alphanumeric, so surrounding
# whitespace is always a stray newline from the paste, never part of it.
secret = secret.strip()

if not secret:
    sys.exit('\nnothing entered -- %s is unchanged' % ENV)
if secret in PLACEHOLDERS:
    sys.exit('\nthat is a placeholder, not the real password')

encoded = quote(secret, safe='')
replacement = '%s://%s:%s@%s' % (scheme, user, encoded, location)

flat = flat[:match.start()] + match.group(1) + replacement + flat[match.end():]
io.open(ENV, 'w', encoding='utf-8', newline='').write(
    flat.replace('\n', '\r\n') if crlf else flat)

print('')
print('Written.')
print('  password : %d characters' % len(secret))
print('  encoding : %s' % ('percent-encoded for the URI'
                           if encoded != secret else 'no special characters'))
print('')
print('Next: put the same value on Vercel and redeploy --')
print('  vercel env rm MONGO_URI production --yes')
print("  grep '^MONGO_URI=' .env | cut -d= -f2- | vercel env add MONGO_URI production")
print('  vercel deploy --prod')
print('')
